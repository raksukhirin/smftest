# gen-sn.ps1 - generates src\EdiLicensed.cs (SHA-256 hashes) from src\sn.txt (list of customer serials)
# Called by build.bat before compiling. ASCII only on purpose (Windows PowerShell 5.1 reads BOM-less files as ANSI).
#   sn.txt: one customer per line:  SERIAL   # customer name      (blank lines and lines starting with # are ignored)
param(
    [string]$In  = (Join-Path $PSScriptRoot 'src\sn.txt'),
    [string]$Out = (Join-Path $PSScriptRoot 'src\EdiLicensed.cs')
)
$ErrorActionPreference = 'Stop'

$sha = [System.Security.Cryptography.SHA256]::Create()
$items = New-Object System.Collections.ArrayList
$seen = @{}
if (Test-Path $In) {
    $n = 0
    foreach ($raw in [System.IO.File]::ReadAllLines($In, [System.Text.Encoding]::UTF8)) {
        $n++
        $line = $raw.Trim()
        if ($line -eq '' -or $line.StartsWith('#')) { continue }
        $name = ''
        $hash = $line.IndexOf('#')
        if ($hash -ge 0) { $name = $line.Substring($hash + 1).Trim(); $line = $line.Substring(0, $hash).Trim() }
        $serial = ($line -split '\s+')[0].Trim().ToUpperInvariant()
        if ($serial -eq '') { continue }
        $bytes = [System.Text.Encoding]::UTF8.GetBytes('SMF-EDI|' + $serial)
        $h = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') })
        if ($seen.ContainsKey($h)) { Write-Warning "sn.txt line ${n}: duplicate serial ignored"; continue }
        $seen[$h] = $true
        [void]$items.Add(@{ Hash = $h; Name = $name })
    }
} else {
    Write-Warning "sn.txt not found ($In) - no customer will have EDI"
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// GENERATED by gen-sn.ps1 from src\sn.txt - do not edit (changes are overwritten at every build)')
[void]$sb.AppendLine('// Customers who bought EDI: SHA-256 hash of the serial (the real serial is not stored in the program)')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace BLScan')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    public static class EdiLicensed')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        public static readonly HashSet<string> Hashes = new HashSet<string>')
[void]$sb.AppendLine('        {')
foreach ($i in $items) {
    # the customer name is not written to the generated file
    [void]$sb.AppendLine('            "' + $i.Hash + '",')
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
[System.IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($true)))
Write-Host ("sn.txt: " + $items.Count + " customer serial(s) -> " + $Out)
